def generate_markdown(data):
    """生成标准格式的 Markdown"""
    content = f"# {data['title']}\n\n"
    content += f"## 模块描述\n{data['description']}\n\n"

    for section in data['sections']:
        content += f"## {section['name']}\n\n"

        for func in section.get('functions', []):
            content += f"### {func['name']}\n\n"

            if func.get('positive'):
                content += "#### 正向\n"
                for item in func['positive']:
                    content += f"- {item}\n"
                content += "\n"

            if func.get('negative'):
                content += "#### 反向\n"
                for item in func['negative']:
                    content += f"- {item}\n"
                content += "\n"

            if func.get('boundary'):
                content += "#### 边界值\n"
                for item in func['boundary']:
                    content += f"- {item}\n"
                content += "\n"

    return content


def main():
    print("=" * 60)
    print("生成测试点分析知识库文件")
    print("=" * 60)

    testpoint_data = get_testpoint_data()
    print(f"读取到 {len(testpoint_data)} 个模块")

    for name in testpoint_data.keys():
        print(f"  - {name}")

    testpoint_dir = os.path.join(KNOWLEDGE_BASE_DIR, "testpoint")
    os.makedirs(testpoint_dir, exist_ok=True)
    print(f"\n目标目录: {testpoint_dir}")

    generated = 0
    skipped = 0

    for filename, data in testpoint_data.items():
        content = generate_markdown(data)
        filepath = os.path.join(testpoint_dir, filename + ".md")

        # 检查文件是否已存在
        if os.path.exists(filepath):
            print(f"⚠️ 文件已存在，跳过: {filename}.md")
            skipped += 1
        else:
            with open(filepath, 'w', encoding='utf-8') as f:
                f.write(content)
            print(f"✅ 生成: {filename}.md")
            generated += 1

    print("=" * 60)
    print(f"✅ 共生成 {generated} 个测试点知识库文件")
    print(f"⚠️ 跳过 {skipped} 个已存在的文件")
    print(f"📁 保存位置: {testpoint_dir}")


if __name__ == "__main__":
    main()